"""Data preparation (spec sections 18, 22, 27): synthetic fixtures, deterministic macroblock
crops of real sources, and schema-conformant manifest rows. Crop positions come from a seeded
grid choice made before any codec runs (selection never looks at compression results)."""

from __future__ import annotations

import datetime as _dt
from pathlib import Path

import numpy as np

from cape import synthetic as syn
from cape.canonical import to_canonical, voxel_sha256
from cape.io import file_sha256, read_raw, save_canonical
from cape.provenance import ROOT

SEED = 20261105
CRACKLE_URL = "https://github.com/seung-lab/crackle"
CRACKLE_SHA = "14b39b196a14b3b1ba7d1cd34f350c324308000f"


def rel(p: Path) -> str:
    try:
        return p.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(p.resolve())


def make_row(canon: np.ndarray, path: Path, *, sample_id: str, family_id: str, source_id: str, specimen_id,
             macroblock_id: str, split: str, is_synthetic: bool, selection_rule: str, source_url=None,
             source_version=None, license: str = "unknown", citation=None, array_key=None, source_axes=None,
             bbox_xyz=None, spacing_xyz=None, original_path=None, original_file_sha256=None,
             null_reasons: dict | None = None) -> dict:
    save_canonical(path, canon)
    return {
        "sample_id": sample_id, "family_id": family_id, "source_id": source_id, "specimen_id": specimen_id,
        "macroblock_id": macroblock_id, "split": split, "path": rel(path), "original_path": original_path,
        "source_url": source_url, "source_version": source_version, "license": license, "citation": citation,
        "array_key": array_key, "axes": "ZYX", "source_axes": source_axes, "dtype": str(canon.dtype),
        "shape": [int(v) for v in canon.shape], "bbox_xyz": bbox_xyz, "spacing_xyz": spacing_xyz,
        "original_file_sha256": original_file_sha256, "voxel_sha256": voxel_sha256(canon),
        "is_synthetic": is_synthetic, "selection_rule": selection_rule, "null_reasons": null_reasons or {},
        "prepared_at": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
    }


# ----------------------------------------------------------------- synthetic set
def synthetic_specs(seed: int = SEED) -> list[tuple[str, np.ndarray]]:
    """The spec section 22 families (small sizes; correctness + adversarial)."""
    out = [
        ("vertical_cylinders", syn.vertical_cylinders((32, 64, 64), n=14, seed=seed)),
        ("walking_cylinders", syn.walking_cylinders((32, 64, 64), n=10, seed=seed + 1)),
        ("branching", syn.branching((32, 64, 64), n=6, seed=seed + 2)),
        ("dense_voronoi", syn.dense_drifting_voronoi((32, 64, 64), n_seeds=50, seed=seed + 3)),
        ("blocky_u16", syn.blocky((32, 64, 64), n_labels=20, dtype=np.uint16, seed=seed + 4)),
        ("checkerboard", syn.checkerboard((8, 32, 32))),
        ("noise", syn.noise((16, 32, 32), n_labels=6, seed=seed + 5)),
        ("single_label", syn.single_label((16, 32, 32))),
        ("all_background", syn.all_background((16, 32, 32))),
        ("all_distinct", syn.all_distinct((4, 16, 16))),
        ("disconnected_same_id", syn.disconnected_same_id((16, 32, 32), seed=seed + 6)),
        ("single_slice", syn.single_slice((1, 64, 64), seed=seed + 7)),
        ("depth_255", syn.depth_boundary(256)),
        ("depth_256", syn.depth_boundary(257)),
        ("depth_257", syn.depth_boundary(258)),
        ("large_uint64_ids", syn.large_ids((16, 32, 32), seed=seed + 8)),
        ("count_width_255", syn.isolated_components(255, depth=2)),
        ("count_width_256", syn.isolated_components(256, depth=2)),
        ("count_width_adversarial", syn.count_width_adversarial()),
    ]
    return out


def synthetic_rows(out_dir: Path, seed: int = SEED, families: list[str] | None = None) -> list[dict]:
    rows = []
    for name, vol in synthetic_specs(seed):
        if families and name not in families:
            continue
        canon, _ = to_canonical(vol, "ZYX")
        rows.append(make_row(canon, out_dir / f"syn_{name}.npy", sample_id=f"syn_{name}", family_id="synthetic",
                             source_id=f"synthetic:{name}", specimen_id=None, macroblock_id=f"syn_{name}",
                             split="synthetic", is_synthetic=True, license="generated by this project",
                             selection_rule=f"cape.data_prep.synthetic_specs seed={seed}",
                             source_url=None, source_version="cape.synthetic",
                             null_reasons={"specimen_id": "synthetic", "source_url": "generated locally",
                                           "original_file_sha256": "generated in memory"}))
    return rows


# ------------------------------------------------------------- macroblock crops
def macroblock_grid(shape_xyz, crop_xyz, n: int, seed: int = SEED, exclude=()) -> list[list[list[int]]]:
    """Deterministic, spatially separated macroblocks: tile the volume with non-overlapping crop-sized
    cells (dropping partial edge cells) and draw n distinct cells with a seeded RNG."""
    cells = []
    counts = [shape_xyz[i] // crop_xyz[i] for i in range(3)]
    for ix in range(counts[0]):
        for iy in range(counts[1]):
            for iz in range(counts[2]):
                cells.append((ix, iy, iz))
    cells = [c for c in cells if c not in set(exclude)]
    if not cells:
        return []
    rng = np.random.default_rng(seed)
    pick = rng.choice(len(cells), size=min(n, len(cells)), replace=False)
    out = []
    for k in sorted(int(i) for i in pick):
        ix, iy, iz = cells[k]
        out.append([[ix * crop_xyz[0], (ix + 1) * crop_xyz[0]], [iy * crop_xyz[1], (iy + 1) * crop_xyz[1]],
                    [iz * crop_xyz[2], (iz + 1) * crop_xyz[2]]])
    return out


def crackle_sample_rows(out_dir: Path, crop_xyz=(128, 128, 64), per_file: dict | None = None,
                        seed: int = SEED) -> list[dict]:
    """Crops of the Crackle repository samples (development split). Source arrays are (x,y,z)."""
    per_file = per_file or {"connectomics": 2, "ws": 1}
    rows = []
    for key, n in per_file.items():
        src = ROOT / "vendor" / "crackle" / f"{key}.npy.cpso.gz"
        if not src.exists():
            continue
        full = read_raw(src)
        sha = file_sha256(src)
        boxes = macroblock_grid(list(full.shape), list(crop_xyz), n, seed + (0 if key == "connectomics" else 1))
        for b in boxes:
            sub = full[b[0][0]:b[0][1], b[1][0]:b[1][1], b[2][0]:b[2][1]]
            canon, _ = to_canonical(np.asarray(sub), "XYZ")
            mb = f"x{b[0][0]}_y{b[1][0]}_z{b[2][0]}"
            sid = f"crackle_{key}_{mb}_{crop_xyz[0]}x{crop_xyz[1]}x{crop_xyz[2]}"
            rows.append(make_row(canon, out_dir / f"{sid}.npy", sample_id=sid, family_id="crackle_samples",
                                 source_id=f"crackle:{key}", specimen_id=f"crackle:{key}", macroblock_id=mb,
                                 split="development", is_synthetic=False, source_url=CRACKLE_URL,
                                 source_version=CRACKLE_SHA,
                                 license="unknown (data in BSD-3 code repository; data terms not stated)",
                                 citation="S1", array_key=None, source_axes="XYZ", bbox_xyz=b,
                                 spacing_xyz=None, original_path=rel(src), original_file_sha256=sha,
                                 selection_rule=f"macroblock_grid crop={list(crop_xyz)} seed={seed} n={n}",
                                 null_reasons={"spacing_xyz": "not stated by the repository"}))
        del full
    return rows
