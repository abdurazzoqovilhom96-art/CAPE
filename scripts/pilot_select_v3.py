def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--phase", type=int, choices=(1, 2), required=True)
    ap.add_argument("--runs", nargs="*")
    ap.add_argument("--rerun", nargs="*")
    ap.add_argument("--quality-check")
    a = ap.parse_args(argv)
    proto = yaml.safe_load(PROTO.read_text(encoding="utf-8"))
    if a.phase == 1:
        return phase1(a, proto)
    if not a.quality_check:
        print("--quality-check <run> required in phase 2", file=sys.stderr)
        return 2
    return phase2(a, proto)


if __name__ == "__main__":
    sys.exit(main())
