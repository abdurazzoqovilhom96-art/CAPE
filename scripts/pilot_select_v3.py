"""CAPE v3 stage SELECT (plan CAPE v3, sections 10 and 20): apply the gates fixed in configs/v3_development.yaml to
the development runs. Nothing here looks at SNEMI3D.

    phase 1  python scripts/pilot_select_v3.py --phase 1 --runs core=<run> scale=<run> quality=<run> tracks=<run>
             [--rerun core=<run> scale=<run>]
             -> per-module FAST / MEMORY / INCONCLUSIVE decisions, M3a / M3b / M4 results and grid choice;
                writes the selected method definitions into configs/v3_methods.yaml (generated block) and
                configs/v3_dev_quality_check.yaml (the QUALITY composite still has to be measured);
                if a module is INCONCLUSIVE and no rerun was given: writes configs/v3_dev_*_rerun.yaml and exits 3
    phase 2  python scripts/pilot_select_v3.py --phase 2 --quality-check <run>
             -> QUALITY gate on the composite; final analysis/v3_select/selected_methods.json

Exit: 0 decided, 3 rerun required (inconclusive rule), 2 input error.
"""

