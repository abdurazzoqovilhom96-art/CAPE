def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def parse_runs(items) -> dict:
    out = {}
    for it in items or []:
        k, _, v = it.partition("=")
        out[k] = v
    return out


def dev_cluster(c: dict) -> str:
    """Development clustering: nested scaling crops share one source (plan 12.1: nested crops are one overlap
    cluster); every other crop clusters by its macroblock."""
    if str(c["sample_id"]).startswith("scale_"):
        return "scale:" + str(c["source_id"])
    return str(c["macroblock_id"] or c["sample_id"])


def merged(*cell_dicts) -> dict:
    out = {}
    for d in cell_dicts:
        for k, v in d.items():
            if k in out:
                raise SystemExit(f"duplicate cell {k} across runs")
            out[k] = v
    return out


# ------------------------------------------------------------------------------------------------ correctness
def correctness(all_cells: dict, proto: dict) -> dict:
    etalon = proto["gates"]["correctness"]["byte_preserving_equal_to"]
    bp = [m["single"] for m in proto["modules"].values() if "single" in m] + \
         [m["leave_one_out"] for m in proto["modules"].values() if "leave_one_out" in m] + \
         ["cape_v3_all_m0", "cape_v3_off_m0"]
    mism, checked = [], 0
    for (s, m), c in all_cells.items():
        if m not in bp:
            continue
        e = all_cells.get((s, etalon))
        if e is None:
            continue
        checked += 1
        if c["total_bytes"] is None or e["total_bytes"] is None or c["total_bytes"] != e["total_bytes"]:
            mism.append({"sample_id": s, "method": m, "bytes": c["total_bytes"], "etalon": e["total_bytes"]})
    not_ok = []
    for (s, m), c in all_cells.items():
        bad = {k: v for k, v in c["statuses"].items() if k != "OK"}
        if bad:
            not_ok.append({"sample_id": s, "method": m, "statuses": bad, "reasons": c["reasons"][:2]})
    return {"byte_preserving_checked": checked, "byte_mismatches": mism, "non_ok_cells": not_ok,
            "pass": not mism and not any(r["method"] in bp for r in not_ok)}


# ------------------------------------------------------------------------------------------------ FAST gates
def fast_gate(cells: dict, mod: str, spec: dict, gate: dict, mem_gate: dict) -> dict:
    loo = paired(cells, "cape_v3_all_m0", spec["leave_one_out"], cluster=dev_cluster)
    single = paired(cells, spec["single"], "cape_v3_off_m0", cluster=dev_cluster)
    single_v21 = paired(cells, spec["single"], "cape_v21_fast_m0", cluster=dev_cluster)
    s, lo = loo.get("S_T"), (loo.get("S_T_ci") or [None])[0]
    peak = loo.get("peak_ratio_median")
    point_ok = s is not None and s >= gate["geo_speedup_min"]
    ci_ok = lo is not None and lo > gate["ci_lower_gt"]
    mem_ok = peak is None or peak <= 1 + gate["peak_memory_median_increase_max"]
    bytes_ok = loo.get("bytes_identical", False)
    if not bytes_ok:
        verdict = "FAIL_BYTES"
    elif point_ok and ci_ok and mem_ok:
        verdict = "PASS"
    elif point_ok != ci_ok:
        verdict = "INCONCLUSIVE"
    else:
        verdict = "FAIL"
    memory_profile = (peak is not None and peak <= 1 - mem_gate["peak_reduction_min"]
                      and s is not None and s >= 1 / (1 + mem_gate["time_increase_max"]))
    return {"module": mod, "bit": spec["bit"], "verdict": verdict, "memory_profile": bool(memory_profile),
            "loo_S_T": s, "loo_S_T_ci": loo.get("S_T_ci"), "loo_peak_ratio_median": peak, "loo_n": loo.get("n"),
            "loo_clusters": loo.get("n_clusters"), "loo_slowdowns_gt10pct": loo.get("slowdowns_gt10pct"),
            "loo_source_weighted_S_T": loo.get("source_weighted", {}).get("S_T"),
            "single_S_T_vs_off": single.get("S_T"), "single_S_T_ci_vs_off": single.get("S_T_ci"),
            "single_peak_ratio_vs_off": single.get("peak_ratio_median"),
            "single_S_T_vs_v21": single_v21.get("S_T"), "bytes_identical": bytes_ok,
            "per_sample": loo.get("per_sample", [])}


def quality_results(qc: dict, proto: dict) -> dict:
    g = proto["gates"]["quality"]
    group = g["group"]
    allq = sorted({s for s, _ in qc})

    def eff(new, base, samples):
        p = paired(qc, new, base, samples=samples, cluster=dev_cluster)
        return {"G_B_pct": p.get("G_B_pct"), "time_ratio_total": p.get("time_ratio_total"), "n": p.get("n"),
                "larger": p.get("larger"), "smaller": p.get("smaller"), "equal": p.get("equal"),
                "bytes_identical": p.get("bytes_identical"), "per_sample": p.get("per_sample", [])}

    out = {"group": group, "regimes": {"group": eff("cape_v3_regimes_m0", "cape_v3_all_m0", group),
                                       "corpus": eff("cape_v3_regimes_m0", "cape_v3_all_m0", allq)}}
    gate = eff("cape_v3_regimes_gate_m0", "cape_v3_regimes_m0", allq)
    pruned = [qc[(s, "cape_v3_regimes_gate_m0")]["extra"].get("regime_gate_pruned", 0)
              for s in allq if (s, "cape_v3_regimes_gate_m0") in qc]
    checked = [qc[(s, "cape_v3_regimes_gate_m0")]["extra"].get("regime_gate_checked", 0)
               for s in allq if (s, "cape_v3_regimes_gate_m0") in qc]
    keep_m3a = bool(gate["bytes_identical"] and gate["time_ratio_total"] is not None
                    and gate["time_ratio_total"] < proto["gates"]["m3a_regime_gate"]["keep_if_total_encode_ratio_below"])
    out["M3a"] = {**gate, "regimes_checked": sum(checked), "regimes_pruned": sum(pruned), "keep": keep_m3a,
                  "decision": "KEEP (output-identical, faster)" if keep_m3a else
                  "EXPERIMENTAL (no time saving or bytes differ)"}
    out["M3b"] = {"group": eff("cape_v3_rc_m0", "cape_v3_all_m0", group),
                  "corpus": eff("cape_v3_rc_m0", "cape_v3_all_m0", allq),
                  "regimes_plus_rc_group": eff("cape_v3_regimes_rc_m0", "cape_v3_regimes_m0", group)}
    grid = []
    for m in sorted({m for _, m in qc if m.startswith("cape_v3_rep_")}):
        r, p, a = map(int, re.match(r"cape_v3_rep_r(\d+)_p(\d+)_a(\d+)_m0", m).groups())
        e = eff(m, "cape_v3_all_m0", group)
        grid.append({"method": m, "R": r, "pool": p, "attempts": a, **{k: e[k] for k in
                     ("G_B_pct", "time_ratio_total", "n", "larger", "smaller", "equal")}})
    lim = g["max_total_encode_ratio_vs_fast"]
    ok = [x for x in grid if x["time_ratio_total"] is not None and x["time_ratio_total"] <= lim and not x["larger"]]
    choice = None
    if ok:
        best = max(x["G_B_pct"] for x in ok)
        if best > 0:
            tied = [x for x in ok if x["G_B_pct"] == best]
            choice = sorted(tied, key=lambda x: (x["R"], x["pool"], x["attempts"]))[0]
    out["M4"] = {"grid": grid, "choice": choice, "rule": proto["gates"]["m4_grid_choice"],
                 "decision": f"grid point {choice['method']}" if choice else "EXPERIMENTAL (no grid point with a saving "
                                                                           "inside the QUALITY time gate)"}
    return out


def tracks_summary(tc: dict) -> dict:
    allt = sorted({s for s, _ in tc})
    rows = []
    for new, base in [("cape_v3_all_m0", "v3_weighted_greedy_fast_m0"), ("cape_v3_all_m0", "v3_greedy_local_fast_m0"),
                      ("cape_v3_all_m0", "v3_exact_only_fast_m0"), ("v3_greedy_local_b4_fast_m0", "v3_greedy_local_fast_m0"),
                      ("v3_weighted_greedy_rc_m0", "v3_weighted_greedy_fast_m0"), ("cape_v3_rc_m0", "cape_v3_all_m0"),
                      ("cape_v3_all_m0", "v3_cape_noreduce_fast_m0"),
                      ("v3_weighted_greedy_fast_m0", "v3_weighted_greedy_noreduce_fast_m0"),
                      ("cape_v3_all_m0", "crackle_pins_opt_corrected_m0"), ("cape_v3_all_m0", "crackle_flat_m0"),
                      ("cape_v3_all_m0", "crackle_pins_fast_m0"), ("cape_v3_all_m0", "cape_v21_fast_m0"),
                      ("safe_v3_archive_m0_zstd9", "safe_stock_m0_zstd9"),
                      ("safe_v3_archive_m0_zstd9", "crackle_flat_m0+zstd9"),
                      ("safe_v3_archive_m0_zstd3", "safe_stock_m0_zstd3"), ("cape_v3_all_m5", "cape_v21_fast_m5")]:
        p = paired(tc, new, base, samples=allt, cluster=dev_cluster)
        rows.append({"new": new, "base": base, "n": p.get("n"), "G_B_pct": p.get("G_B_pct"), "G_B_ci": p.get("G_B_ci"),
                     "S_T": p.get("S_T"), "S_T_ci": p.get("S_T_ci"), "smaller": p.get("smaller"),
                     "equal": p.get("equal"), "larger": p.get("larger")})
    gaps = []
    for m in ("v3_cape_certified_m0", "v3_cape_certified_rc_m0", "v3_weighted_greedy_certified_m0"):
        for s in allt:
            c = tc.get((s, m))
            if c and c["ub"] and c["lb"] is not None:
                gaps.append({"method": m, "sample_id": s, "ub": c["ub"], "lb": c["lb"],
                             "gap_pct": 100 * (c["ub"] - c["lb"]) / c["ub"], "valid": all(c["cert_valid"])})
    return {"pairs": rows, "certificate_gaps": gaps}


def write_generated_methods(fast_mask: int, mem_mask: int | None, quality: dict | None) -> list[str]:
    """Append (or replace) the generated block in configs/v3_methods.yaml with the selected definitions."""
    def m(desc, opts, role="new", wrappable=False, cats=("K1", "K2", "K3"), adapter="cape_native", exp=False):
        d = {"adapter": adapter, "options": opts, "family": "crackle_format", "categories": list(cats),
             "panels": ["B"], "wrappable": wrappable, "role": role, "description": desc}
        if exp:
            d["experimental"] = True
        return d

    sel = {
        "cape_v3_fast_m0": m(f"v3 FAST (selected impl_mask {fast_mask}) - the v3 primary method", {**FAST_OPTS,
                             "impl_mask": fast_mask}, wrappable=True),
        "cape_v3_fast_m5": m(f"v3 FAST, Markov order 5 (secondary)", {**FAST_OPTS, "markov_model_order": 5,
                             "impl_mask": fast_mask}),
        "cape_v3_certified_m0": m("v3 CERTIFIED - the v3 FAST stream (byte-identical) + LB over all depth regimes",
                                  {**FAST_OPTS, "certificate": "all_regimes", "impl_mask": fast_mask},
                                  cats=("K1", "K2", "K6")),
        "v3_fast_weighted_greedy_m0": m("matched baseline on the v3 FAST infrastructure: optimized weighted greedy",
                                        {**FAST_OPTS, "impl_mask": fast_mask, "use_exact": False, "use_local": False},
                                        role="internal", cats=("K1", "K2", "K5")),
        "v3_fast_greedy_local_m0": m("matched baseline on the v3 FAST infrastructure: weighted greedy + local search",
                                     {**FAST_OPTS, "impl_mask": fast_mask, "use_exact": False, "use_local": True},
                                     role="internal", cats=("K1", "K2", "K5")),
        "v3_fast_weighted_greedy_certified_m0": m("matched certificate: weighted greedy + the same all-regime dual LB",
                                                  {**FAST_OPTS, "certificate": "all_regimes", "impl_mask": fast_mask,
                                                   "use_exact": False, "use_local": False}, role="internal",
                                                  cats=("K1", "K2", "K6")),
        "safe_v3_fast_m0_zstd9": m("SAFE-CAPE v3: min(zstd9(flat), zstd9(v3 FAST))", {"zstd": "zstd9", **{k: v for k, v in
                                   FAST_OPTS.items() if k != "format_policy"}, "impl_mask": fast_mask},
                                   role="internal", cats=("K1", "K3"), adapter="safe_archive"),
        "safe_v3_fast_m0_zstd3": m("SAFE-CAPE v3: min(zstd3(flat), zstd3(v3 FAST)) (secondary)", {"zstd": "zstd3", **{
                                   k: v for k, v in FAST_OPTS.items() if k != "format_policy"}, "impl_mask": fast_mask},
                                   role="internal", cats=("K1", "K3"), adapter="safe_archive"),
    }
    if mem_mask is not None and mem_mask != fast_mask:
        sel["cape_v3_memory_m0"] = m(f"v3 MEMORY profile (impl_mask {mem_mask}): FAST + memory-only modules",
                                     {**FAST_OPTS, "impl_mask": mem_mask}, role="internal")
    if quality is not None:
        q = {**FAST_OPTS, "depth_policy": "full_width_first", "impl_mask": fast_mask, **quality}
        sel["cape_v3_quality_m0"] = m("v3 QUALITY candidate: v3 FAST + depth regimes + "
                                      + ", ".join(k for k in quality if k in ("regime_gate", "rc_fixing", "repair")),
                                      q, role="internal", exp=True)
    text = METHODS_FILE.read_text(encoding="utf-8")
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip("\n") + "\n"
    block = yaml.safe_dump(sel, sort_keys=False, default_flow_style=None, width=118)
    block = "\n".join("  " + line if line else line for line in block.splitlines())
    text += f"{BEGIN}\n{block}\n{END}\n"
    METHODS_FILE.write_text(text, encoding="utf-8")
    return list(sel)


def write_run_config(name: str, desc: str, manifest: str, methods: list[str], repeats: int, primary: tuple,
                     mem: bool) -> str:
    cfg = {"schema_version": 1, "project": "CAPE-Pins", "seed": 20261106, "mode": "development",
           "description": desc, "input": {"manifest": manifest, "splits": ["development"], "require_real_data": True},
           "benchmark": {"warmups": 2, "repeats": repeats, "external_wrappers": ["none"], "task_timeout_s": 3600,
                         "memory_profile_separate": mem},
           "methods": methods, "panels": ["B"], "primary": {"new": primary[0], "baseline": primary[1]},
           "oracle": {"enabled": False}}
    p = ROOT / "configs" / f"{name}.yaml"
    p.write_text(f"# GENERATED by scripts/pilot_select_v3.py ({now()}) - development only\n"
                 + yaml.safe_dump(cfg, sort_keys=False, width=118), encoding="utf-8")
    return p.relative_to(ROOT).as_posix()


def phase1(args, proto) -> int:
    runs = parse_runs(args.runs)
    missing = [k for k in ("core", "scale", "quality", "tracks") if k not in runs]
    if missing:
        print(f"missing runs: {missing}", file=sys.stderr)
        return 2
    core, scale = load_cells(runs["core"]), load_cells(runs["scale"])
    qc, tc = load_cells(runs["quality"]), load_cells(runs["tracks"])
    rerun = parse_runs(args.rerun)
    impl = merged(core, scale)
    corr = correctness(merged(core, scale), proto)
    gate, mem_gate = proto["gates"]["fast"], proto["gates"]["memory_profile"]
    mods = {k: v for k, v in proto["modules"].items() if "leave_one_out" in v}
    decisions = {k: fast_gate(impl, k, v, gate, mem_gate) for k, v in mods.items()}
    rerun_info = None
    if rerun:
        rr = merged(load_cells(rerun["core"]), load_cells(rerun["scale"]))
        for k, d in decisions.items():
            if d["verdict"] == "INCONCLUSIVE":
                d2 = fast_gate(rr, k, mods[k], gate, mem_gate)
                d2["first_verdict"] = "INCONCLUSIVE"
                if d2["verdict"] == "INCONCLUSIVE":
                    d2["verdict"] = "FAIL_INCONCLUSIVE_AFTER_RERUN"
                decisions[k] = d2
        rerun_info = rerun
    elif any(d["verdict"] == "INCONCLUSIVE" for d in decisions.values()):
        inc = [k for k, d in decisions.items() if d["verdict"] == "INCONCLUSIVE"]
        methods = ["cape_v21_fast_m0", "cape_v3_all_m0"] + [mods[k]["leave_one_out"] for k in inc]
        cfgs = {"core": write_run_config("v3_dev_core_rerun", f"v3 inconclusive rule: 15-repeat rerun for {inc}",
                                         "data/manifests/v3_dev_core.jsonl", methods, 15, methods[1::-1], True),
                "scale": write_run_config("v3_dev_scale_rerun", f"v3 inconclusive rule: 15-repeat rerun for {inc}",
                                          "data/manifests/scaling_v21.jsonl", methods, 15, methods[1::-1], True)}
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / "rerun_required.json").write_text(json.dumps({"modules": inc, "configs": cfgs,
                                                             "manifests": {"core": "data/manifests/v3_dev_core.jsonl",
                                                                           "scale": "data/manifests/scaling_v21.jsonl"},
                                                             "at": now()}, indent=2), encoding="utf-8")
        print(f"INCONCLUSIVE modules {inc}: rerun required -> {cfgs}")
        return 3
    fast_mask = 31 + sum(d["bit"] for d in decisions.values() if d["verdict"] == "PASS")
    mem_extra = sum(d["bit"] for d in decisions.values() if d["verdict"] != "PASS" and d["memory_profile"])
    mem_mask = fast_mask + mem_extra if mem_extra else None
    q = quality_results(qc, proto)
    composite = {"rc_fixing": True}
    if q["M3a"]["keep"]:
        composite["regime_gate"] = True
    if q["M4"]["choice"]:
        ch = q["M4"]["choice"]
        composite.update(repair=True, repair_max_r=ch["R"], repair_max_pool=ch["pool"], repair_attempts=ch["attempts"])
    tr = tracks_summary(tc)
    ids = write_generated_methods(fast_mask, mem_mask, composite)
    check_cfg = write_run_config(
        "v3_dev_quality_check", "v3 SELECT phase 2: QUALITY composite vs selected FAST on the QUALITY panel crops",
        "data/manifests/v3_dev_quality.jsonl", ["cape_v3_fast_m0", "cape_v3_quality_m0"], 3,
        ("cape_v3_quality_m0", "cape_v3_fast_m0"), False)
    sel = {"phase": 1, "at": now(), "runs": runs, "rerun": rerun_info, "correctness": corr,
           "fast_modules": {k: {kk: vv for kk, vv in d.items() if kk != "per_sample"} for k, d in decisions.items()},
           "fast_impl_mask": fast_mask, "memory_impl_mask": mem_mask, "quality_components": q_no_samples(q),
           "quality_composite_options": composite, "quality_check_config": check_cfg, "tracks": tr,
           "generated_methods": ids, "overall_all_vs_v21": {k: v for k, v in paired(
               impl, "cape_v3_all_m0", "cape_v21_fast_m0", cluster=dev_cluster).items() if k != "per_sample"},
           "build_drift_off_vs_v21": {k: v for k, v in paired(
               impl, "cape_v3_off_m0", "cape_v21_fast_m0", cluster=dev_cluster).items() if k != "per_sample"}}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "selected_methods.json").write_text(json.dumps(sel, indent=2, default=str), encoding="utf-8")
    write_csv(OUT / "fast_gate_per_sample.csv", [{"module": k, **p} for k, d in decisions.items() for p in d["per_sample"]])
    write_csv(OUT / "status_by_method.csv", status_table(merged(core, scale)) + status_table(qc) + status_table(tc))
    write_csv(OUT / "m4_grid.csv", q["M4"]["grid"])
    write_csv(OUT / "tracks_pairs.csv", tr["pairs"])
    write_csv(OUT / "certificate_gaps_dev.csv", tr["certificate_gaps"])
    write_report(sel)
    print(json.dumps({"fast_impl_mask": fast_mask, "memory_impl_mask": mem_mask,
                      "verdicts": {k: d["verdict"] for k, d in decisions.items()}, "composite": composite,
                      "correctness_pass": corr["pass"]}, indent=1))
    return 0


def q_no_samples(q: dict) -> dict:
    def strip(x):
        if isinstance(x, dict):
            return {k: strip(v) for k, v in x.items() if k != "per_sample"}
        if isinstance(x, list):
            return [strip(v) for v in x]
        return x

    return strip(q)


def phase2(args, proto) -> int:
    sel = json.loads((OUT / "selected_methods.json").read_text(encoding="utf-8"))
    cells = load_cells(args.quality_check)
    g = proto["gates"]["quality"]
    grp = paired(cells, "cape_v3_quality_m0", "cape_v3_fast_m0", samples=g["group"], cluster=dev_cluster)
    corpus = paired(cells, "cape_v3_quality_m0", "cape_v3_fast_m0", cluster=dev_cluster)
    saving = grp.get("G_B") or 0.0
    ratio = grp.get("time_ratio_total")
    never_larger = corpus.get("larger", 1) == 0
    passed = (saving >= g["min_total_raw_saving"] and ratio is not None and ratio <= g["max_total_encode_ratio_vs_fast"]
              and never_larger)
    sel["phase"] = 2
    sel["quality_gate"] = {"run": args.quality_check, "group_G_B_pct": grp.get("G_B_pct"),
                           "group_time_ratio_total": ratio, "corpus_G_B_pct": corpus.get("G_B_pct"),
                           "corpus_time_ratio_total": corpus.get("time_ratio_total"),
                           "corpus_larger": corpus.get("larger"), "never_larger": never_larger,
                           "thresholds": {"min_total_raw_saving": g["min_total_raw_saving"],
                                          "max_total_encode_ratio_vs_fast": g["max_total_encode_ratio_vs_fast"]},
                           "passed": passed,
                           "decision": "QUALITY profile selected (cape_v3_quality_m0)" if passed else
                           "no QUALITY default: the composite stays exploratory (reported, not a v3 mode)"}
    sel["quality_selected"] = passed
    sel["at_phase2"] = now()
    (OUT / "selected_methods.json").write_text(json.dumps(sel, indent=2, default=str), encoding="utf-8")
    write_csv(OUT / "quality_check_per_sample.csv", corpus.get("per_sample", []))
    write_report(sel)
    print(json.dumps(sel["quality_gate"], indent=1, default=str))
    return 0


