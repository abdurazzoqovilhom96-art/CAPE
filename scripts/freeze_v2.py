"""Freeze the v2 test protocol from the v2 PILOT run (pre-registered rule, written before the pilot).

Rule (plan v2, user task 7):
  1. Candidates: safe_refine_e{8,24,64}_m0_zstd9 against SAFE-ARCHIVE safe_archive_m0_zstd9, on the
     pilot's real samples only; every row must be OK (decoded voxel-exact) or the variant is excluded.
  2. gain(e) = sum(SAFE bytes) - sum(variant bytes).
  3. If no variant has gain > 0, the declared default e = 24 is frozen and a null result is expected.
     Otherwise the SMALLEST e with gain(e) >= 0.9 * max gain is frozen (cheapest near-best budget).
  4. Moves stay unpin + anchor (the single-move ablations are reported, they do not change the rule).
The frozen test config (configs/test_v2_frozen.yaml) and the evidence (analysis/v2_freeze/freeze.json)
are written; the test manifest is fixed beforehand (data/manifests/test_v2_unseen.jsonl).

    python scripts/freeze_v2.py --pilot-run results/<run_id>
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

BUDGETS = (8, 24, 64)
DEFAULT_BUDGET = 24
SAFE = "safe_archive_m0_zstd9"

TEST_TEMPLATE = """# GENERATED by scripts/freeze_v2.py from pilot run {pilot} - do not edit by hand.
# Frozen v2 test on UNSEEN crops of SEEN volumes (CREMI B/C slices z 64-123, zero voxel overlap with any
# earlier measurement). Not an independent acquisition: within-volume generalization only.
#   .\\run_experiment.cmd --stage all --config ".\\configs\\test_v2_frozen.yaml" --manifest ".\\data\\manifests\\test_v2_unseen.jsonl"
schema_version: 1
project: CAPE-Pins
seed: 20261105
mode: benchmark
description: v2 frozen test (unseen CREMI B/C crops of seen volumes; refinement budget e={budget} frozen from the pilot)
input:
  manifest: data/manifests/test_v2_unseen.jsonl
  splits: [heldout]
  require_real_data: true
benchmark:
  repeats: 7
  external_wrappers: [none, zstd3, zstd9]
methods: [safe_refine_e{budget}_m0_zstd9, safe_archive_m0_zstd9, safe_refine_e{budget}_m0_zstd3, safe_archive_m0_zstd3,
          safe_refine_e{budget}_m5_zstd9, safe_archive_m5_zstd9, safe_refine_e{budget}_m5_zstd3, safe_archive_m5_zstd3,
          cape_fast_m0, cape_fast_m5, cape_certified_m0, cape_m0, cape_m0_legacy, crackle_flat_m0, crackle_flat_m5,
          crackle_pins_opt_m0, crackle_pins_opt_m5, crackle_pins_opt_corrected_m0, crackle_vendor_pins_opt_m0,
          cape_core, stock_cover, weighted_greedy]
panels: [A, B]
primary:
  new: safe_refine_e{budget}_m0_zstd9
  baseline: safe_archive_m0_zstd9
oracle:
  enabled: false
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pilot-run", required=True)
    args = ap.parse_args(argv)
    from cape.config import load_run_config
    from cape.result_store import atomic_write_text, now_iso

    run = Path(args.pilot_run) if Path(args.pilot_run).is_absolute() else ROOT / args.pilot_run
    rm = json.loads((run / "run_manifest.json").read_text(encoding="utf-8"))
    if rm.get("status") != "COMPLETE":
        print(f"BLOCKED: pilot run {run.name} is {rm.get('status')}, not COMPLETE", file=sys.stderr)
        return 3
    bytes_of: dict = defaultdict(dict)
    bad: dict = defaultdict(int)
    for r in csv.DictReader(open(run / "05_raw_metrics" / "results.csv", encoding="utf-8")):
        if r["panel"] != "B" or r.get("is_synthetic") in ("True", "true") or (r.get("wrapper") or "none") != "none":
            continue
        if r["status"] != "OK":
            bad[r["method_id"]] += 1
            continue
        bytes_of[r["method_id"]][r["sample_id"]] = int(float(r["total_bytes"]))
    samples = sorted(bytes_of.get(SAFE, {}))
    gains = {}
    for e in BUDGETS:
        mid = f"safe_refine_e{e}_m0_zstd9"
        if bad.get(mid) or not all(s in bytes_of.get(mid, {}) for s in samples):
            gains[e] = None
            continue
        gains[e] = sum(bytes_of[SAFE][s] for s in samples) - sum(bytes_of[mid][s] for s in samples)
    valid = {e: g for e, g in gains.items() if g is not None}
    best = max(valid.values()) if valid else None
    if not valid or best <= 0:
        budget, why = DEFAULT_BUDGET, "no variant improved on SAFE-ARCHIVE in the pilot: declared default frozen, null result expected"
    else:
        budget = min(e for e, g in valid.items() if g >= 0.9 * best)
        why = f"smallest budget with gain >= 0.9 x max gain ({best} B)"
    abl = {}
    for mid in ("safe_refine_unpin_e24_m0_zstd9", "safe_refine_anchor_e24_m0_zstd9"):
        if mid in bytes_of and all(s in bytes_of[mid] for s in samples):
            abl[mid] = sum(bytes_of[SAFE][s] for s in samples) - sum(bytes_of[mid][s] for s in samples)
    evidence = {"generated_at": now_iso(), "pilot_run": run.name, "rule": __doc__.split("Rule")[1].split("The frozen")[0].strip(),
                "n_samples": len(samples), "safe_total_bytes": sum(bytes_of[SAFE][s] for s in samples) if samples else None,
                "gain_bytes_by_budget": gains, "non_ok_rows": dict(bad), "ablation_gain_bytes": abl,
                "frozen_budget": budget, "reason": why}
    out = ROOT / "analysis" / "v2_freeze"
    out.mkdir(parents=True, exist_ok=True)
    atomic_write_text(out / "freeze.json", json.dumps(evidence, indent=2))
    cfg_path = ROOT / "configs" / "test_v2_frozen.yaml"
    atomic_write_text(cfg_path, TEST_TEMPLATE.format(pilot=run.name, budget=budget))
    load_run_config(cfg_path)  # validates the generated config
    print(f"frozen budget e={budget} ({why}); gains={gains} -> {cfg_path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
