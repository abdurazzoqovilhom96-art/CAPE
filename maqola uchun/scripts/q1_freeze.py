def write_generated(block: dict) -> None:
    text = METHODS.read_text(encoding="utf-8")
    if GEN_BEGIN in text:
        text = text[:text.index(GEN_BEGIN)]
    body = yaml.safe_dump({"methods": block}, sort_keys=False, width=118).split("\n", 1)[1]
    new = text.rstrip("\n") + "\n" + GEN_BEGIN + body + GEN_END
    if METHODS.read_text(encoding="utf-8") != new:
        METHODS.write_text(new, encoding="utf-8")


def run_config(name: str, desc: str, manifest: str, methods: list[str], repeats: int, wrappers: list[str],
               oracle: bool, mode: str = "benchmark") -> str:
    cfg = {"schema_version": 1, "project": "CAPE-Pins", "seed": SEED, "mode": mode, "description": desc,
           "input": {"manifest": manifest, "splits": ["heldout"], "require_real_data": True},
           "benchmark": {"warmups": 2, "repeats": repeats, "external_wrappers": wrappers, "task_timeout_s": 3600},
           "methods": methods, "panels": ["B"],
           "primary": {"new": "cape_q1_fast_m0", "baseline": "cape_v3frozen_fast_m0"},
           "oracle": {"enabled": oracle}}
    p = ROOT / "configs" / f"{name}.yaml"
    body = yaml.safe_dump(cfg, sort_keys=False, width=118)
    if not (p.exists() and p.read_text(encoding="utf-8").split("\n", 1)[-1] == body):
        p.write_text("# GENERATED by tools/q1_freeze.py - FROZEN Q1 final experiment config\n" + body, encoding="utf-8")
    return f"configs/{name}.yaml"


