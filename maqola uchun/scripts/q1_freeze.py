def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def sha_file(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def method(adapter, options, description, role="internal", wrappable=False, categories=("K1", "K2", "K3")):
    return {"adapter": adapter, "options": options, "family": "crackle_format", "categories": list(categories),
            "panels": ["B"], "wrappable": wrappable, "role": role, "description": description}


